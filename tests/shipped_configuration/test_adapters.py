from __future__ import annotations

import json
import re
import subprocess
import sys
import tomllib
import unittest
from pathlib import Path

from specromancy_engine.adapters import HARNESS_MODES
from specromancy_engine.contracts import RESERVED_COMMANDS
from specromancy_engine.hashing import sha256_bytes
from specromancy_engine.registry import load_registry


ROOT = Path(__file__).resolve().parents[2]
MANIFEST = ROOT / "adapters" / "manifest.json"


class ShippedAdapterTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.manifest_text = MANIFEST.read_text(encoding="utf-8")
        cls.manifest = json.loads(cls.manifest_text)

    def test_adapter_entry_point_reports_no_checkout_drift(self) -> None:
        result = subprocess.run(
            [sys.executable, str(ROOT / "adapters" / "generate.py"), "--check"],
            cwd=ROOT / "docs" / "reference",
            check=False,
            capture_output=True,
            text=True,
        )
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("up to date", result.stdout)

    def test_manifest_covers_harnesses_and_matches_generated_bytes(self) -> None:
        targets = {entry["name"]: entry for entry in self.manifest["targets"]}
        config = tomllib.loads((ROOT / "workflow/adapters.toml").read_text())
        self.assertEqual(config["harnesses"], sorted(HARNESS_MODES))
        self.assertEqual(list(targets), config["harnesses"])
        self.assertEqual(self.manifest["schema_version"], 3)
        self.assertEqual(self.manifest["generator"]["version"], 5)
        generated_by_target = {name: [] for name in HARNESS_MODES}
        for entry in self.manifest["generated"]:
            for target in entry["targets"]:
                generated_by_target[target].append(entry["path"])
            content = (ROOT / entry["path"]).read_bytes()
            self.assertEqual(entry["sha256"], sha256_bytes(content), entry["path"])
        for name, mode in HARNESS_MODES.items():
            with self.subTest(target=name):
                self.assertEqual(targets[name]["mode"], mode)
                self.assertEqual(targets[name]["paths"], generated_by_target[name])

    def test_generated_instruction_files_include_the_authored_instructions(self) -> None:
        instructions = (ROOT / "workflow/instructions.md").read_text(encoding="utf-8").strip()
        for relative in ("AGENTS.md", ".claude/CLAUDE.md", ".github/copilot-instructions.md"):
            with self.subTest(path=relative):
                self.assertIn(instructions, (ROOT / relative).read_text(encoding="utf-8"))

    def test_generated_files_have_provenance_and_no_embedded_checkout_data(self) -> None:
        absolute = re.compile(r"(?:^|[\s'\"`(])/(?:Users|home|private|tmp)/")
        timestamp = re.compile(r"\b20\d{2}-\d{2}-\d{2}T\d{2}:\d{2}")
        workflow_markers = (
            "[[phases.transitions]]",
            "approval_conditions =",
            "max_traversals =",
            "stop_conditions =",
            "terminal_outcomes =",
            "validator =",
        )
        self.assertNotIn("timestamp", self.manifest_text.lower())
        self.assertIsNone(absolute.search(self.manifest_text))
        for entry in self.manifest["generated"]:
            path = ROOT / entry["path"]
            text = path.read_text(encoding="utf-8")
            with self.subTest(path=entry["path"]):
                self.assertIn("Generated by Specromancy from", text[:300])
                self.assertNotIn("bin/specromancy", text)
                self.assertIn("@package/specromancy_engine/resources/adapters/", text[:400])
                self.assertIn("specromancy adapters generate", text[:500])
                self.assertIsNone(absolute.search(text))
                self.assertIsNone(timestamp.search(text))
                self.assertFalse(any(marker in text for marker in workflow_markers))
                if path.name == "SKILL.md":
                    self.assertTrue(text.startswith("---\n# Generated"))

    def test_wrappers_match_shipped_skills_and_supported_commands(self) -> None:
        canonical = {
            path.parent.name for path in (ROOT / ".agents" / "skills").glob("*/SKILL.md")
        }
        mirrored = {
            path.parent.name for path in (ROOT / ".claude" / "skills").glob("*/SKILL.md")
        }
        self.assertEqual(mirrored, canonical)
        wrappers = [
            ROOT / entry["path"]
            for entry in self.manifest["generated"]
            if "commands/" in entry["path"] or entry["path"].endswith(".prompt.md")
        ]
        for path in wrappers:
            commands = re.findall(
                r"(?<![\w/-])specromancy\s+([a-z-]+)", path.read_text(encoding="utf-8")
            )
            with self.subTest(path=path.relative_to(ROOT)):
                self.assertEqual(len(commands), 2)
                self.assertEqual(commands[0], "adapters")
                self.assertTrue(set(commands).issubset(RESERVED_COMMANDS))

    def test_every_registration_has_a_pipeline_launch_skill(self) -> None:
        registry = load_registry(ROOT)
        generated = {entry["path"] for entry in self.manifest["generated"]}
        launch_paths = {
            f".agents/skills/specromancy-{registration.id}/SKILL.md"
            for registration in registry.pipelines
        }
        self.assertEqual({path for path in generated if path.startswith(".agents/skills/specromancy-")}, launch_paths)
        targets = {entry["name"]: entry for entry in self.manifest["targets"]}
        for name, mode in HARNESS_MODES.items():
            if mode == "native":
                self.assertEqual(set(targets[name]["discovery_paths"]), {p for p in generated if p.startswith(".agents/")})
        for registration in registry.pipelines:
            path = ROOT / f".agents/skills/specromancy-{registration.id}/SKILL.md"
            with self.subTest(pipeline=registration.id):
                text = path.read_text(encoding="utf-8")
                self.assertIn(f"--pipeline {registration.id} --json", text)
                self.assertIn("specromancy resume RUN_ID --json", text)


if __name__ == "__main__":
    unittest.main()
